import { AgentSeed } from './vaultSync';
import { isoTimestamp, slugify } from './paths';

/** Mirrors the frontend `Bot` shape (src/types) for custom agents. */
export interface FoundryAgent {
  id: string;
  name: string;
  handle: string;
  role: string;
  ideology: string;
  avatarColor: string;
  badgeColor: string;
  reasoningStyle: string;
  specialty: string;
  quote: string;
  bio: string;
  preferredAttackVectors: string[];
  defensivePhilosophy: string;
  systemInstruction: string;
  isCustom: true;
  autoGenerated: true;
  /** Layer(s) this agent was created to cover. */
  coversLayers: string[];
  createdBy: 'foundry' | 'vault-seed';
  createdAt: string;
  createdBecause: string;
}

