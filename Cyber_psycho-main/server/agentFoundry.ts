// =====================================================================
// AgentFoundry — the council grows where its knowledge is thin.
// ---------------------------------------------------------------------
// The eight built-in agents cover cryptography, consensus, execution,
// economics and L2 state. The Surface Map tracks NINE layers. Governance,
// infrastructure, supply chain and key management have no dedicated
// specialist: their scenarios are argued by borrowed agents, and their
// skills are "trained" on agents whose specialty lies elsewhere.
//
// The foundry measures demand per layer (open coverage gaps weighted by
// severity, plus learned techniques) against the specialists that layer
// has, and — when a layer is under-staffed — creates the missing agent
// from a blueprint. A created agent is a normal custom agent: it appears
// in Agent Studio, can be edited or deleted there, gets a vault profile
// and memory note, and is registered so the skill and intel engines train
// it on its layer.
//
// Agents can also be authored in Obsidian (`type: agent-seed`); the
// foundry imports those first.
//
// Limits: at most one new agent per run and a hard cap on auto-created
// agents, so the roster cannot balloon.
// =====================================================================

import fs from 'fs';
