/** Where a chain usually STARTS, turns, and lands. */
const ENTRY_LAYERS = ['Supply Chain', 'Key Management', 'Infrastructure', 'Governance'];
const PIVOT_LAYERS = ['Cryptography', 'Consensus', 'L2 / Bridge', 'Execution'];
const IMPACT_LAYERS = ['Economic', 'L2 / Bridge', 'Execution', 'Governance', 'Consensus'];

type PathScenario = Omit<ForgedScenario, 'autoGenerated' | 'generatedAt'>;

/**
 * Composes entry → pivot → impact chains from the surface matrix.
 *
 * Every chain crosses three different layers, and the walk is rotated so
 * each entry surface meets a different pivot and impact — the point is
 * breadth of paths, not the single highest-scoring one repeated. A chain
 * is stated as a hypothesis about which precondition each step hands to
 * the next, for the council to confirm or break.
 */
export function defectPaths(coverage: SurfaceCoverage[], limit = 28): PathScenario[] {
  const rank = (c: SurfaceCoverage) =>
    (1 - c.coverage) * (SEVERITY_WEIGHT[c.cell.severity] ?? 0.6) + (c.cell.era === '2030' ? 0.15 : 0);
  const pool = (layers: string[]) =>
    coverage.filter(c => layers.includes(c.cell.layer)).sort((a, b) => rank(b) - rank(a));
  const entries = pool(ENTRY_LAYERS);
  const pivots = pool(PIVOT_LAYERS);
  const impacts = pool(IMPACT_LAYERS);
  const out: PathScenario[] = [];
  const usedPivot = new Map<string, number>();
  const usedImpact = new Map<string, number>();

  /** The least-used candidate; the start is rotated so ties spread across the pool. */
  const least = (cands: SurfaceCoverage[], used: Map<string, number>, offset: number): SurfaceCoverage | undefined => {
    if (cands.length === 0) return undefined;
    const k = offset % cands.length;
    const rotated = [...cands.slice(k), ...cands.slice(0, k)];
    return rotated.sort((a, b) => (used.get(a.cell.id) ?? 0) - (used.get(b.cell.id) ?? 0))[0];
  };

  entries.forEach((e, i) => {
    if (out.length >= limit) return;
    const p = least(pivots.filter(c => c.cell.layer !== e.cell.layer), usedPivot, i * 3);
    if (!p) return;
    const m = least(impacts.filter(c => c.cell.layer !== e.cell.layer && c.cell.layer !== p.cell.layer), usedImpact, i * 5);
    if (!m) return;
    usedPivot.set(p.cell.id, (usedPivot.get(p.cell.id) ?? 0) + 1);
    usedImpact.set(m.cell.id, (usedImpact.get(m.cell.id) ?? 0) + 1);

    const steps = [e, p, m];
    const avgGap = steps.reduce((n, c) => n + (1 - c.coverage), 0) / 3;
    const frontier = steps.filter(c => c.cell.era === '2030').length;
    const shortId = (id: string) => id.replace(/^(f30-)?(consensus|crypto|exec|econ|l2|gov|infra|supply|keys)-/, '').slice(0, 22);

    out.push({
      id: `path-${slugify(steps.map(c => shortId(c.cell.id)).join('--'), 72)}`,
      title: `Defect path: ${e.cell.title} → ${p.cell.title} → ${m.cell.title}`.slice(0, 180),
      category: CATEGORY_BY_LAYER[m.cell.layer] ?? 'Custom',
      briefing: [
        `Cross-layer defect path (${e.cell.layer} → ${p.cell.layer} → ${m.cell.layer}).`,
        `ENTRY — ${e.cell.title}: ${e.cell.hypothesis}`,
        `PIVOT — ${p.cell.title}: ${p.cell.hypothesis}`,
        `IMPACT — ${m.cell.title}: ${m.cell.hypothesis}`,
        `Each step is reviewed by a different team and each looks contained on its own. Argue whether the entry really yields the precondition the pivot needs, whether the pivot really reaches the impact, and which single control — placed at which step — breaks the chain most cheaply.`,
      ].join(' '),
      targetArchitecture: [e, p, m].map(c => c.cell.targetArchitecture).join(' + ').slice(0, 320),
      coreHypothesis: `A weakness in "${e.cell.title}" supplies the precondition for "${p.cell.title}", which in turn makes "${m.cell.title}" reachable — so the system fails across three layers although no single-layer review finds a critical defect.`,
      defaultInvolvedBots: castFor(e.cell.layer, [e.cell.suitedAgents[0], p.cell.suitedAgents[0], m.cell.suitedAgents[0], 'sentinel'])
        .filter((v, idx, a) => a.indexOf(v) === idx),
      origin: 'path',
      layer: m.cell.layer,
      cwe: [e.cell.cwe, p.cell.cwe, m.cell.cwe].filter((v, idx, a) => a.indexOf(v) === idx).join(' → '),
      severity: steps.some(c => c.cell.severity === 'Critical') ? 'Critical' : 'High',
      score: Number(Math.min(0.97, 0.45 + avgGap * 0.4 + frontier * 0.04).toFixed(3)),
      rationale: `Three-layer chain ${e.cell.layer} → ${p.cell.layer} → ${m.cell.layer}${frontier ? ` (${frontier} of 3 steps are 2030-era surfaces)` : ''}; no existing scenario composes these.`,
      pathSteps: steps.map(c => c.cell.id),
    });
  });
  return out;
}

