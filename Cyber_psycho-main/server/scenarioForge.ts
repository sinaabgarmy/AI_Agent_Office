// =====================================================================
// ScenarioForge — debate scenarios generate themselves.
// ---------------------------------------------------------------------
// Four engines can each PROPOSE a scenario (a coverage gap, a harvested
// technique, a graph-derived hypothesis, a hunt target), and the operator
// could promote them one click at a time. Nothing ever did it unattended,
// so the War Room's topic list only grew when someone remembered to press
// the buttons.
//
// The forge collects candidates from every source, including scenarios
// the operator wrote as Obsidian seed notes, then:
//
//   - drops anything the council already has (same id, or a title that is
//     substantially the same as an existing topic)
//   - ranks by how much a debate on it would teach
//   - picks a balanced batch (round-robin across sources, then layers, so
//     one prolific source cannot flood the list)
//   - never regenerates a scenario the operator deleted
//
// Generation stops while a backlog of never-debated auto scenarios exists:
// scenarios are only useful if they get argued.
// =====================================================================

