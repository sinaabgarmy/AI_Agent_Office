const TITLE_STOP = new Set(['the', 'and', 'for', 'with', 'via', 'attack', 'against', 'from', 'into', 'over', 'under', 'vulnerability', 'flaw', 'defect', 'through']);

function titleTokens(title: string): Set<string> {
  return new Set(
    title.toLowerCase().replace(/[^a-z0-9]+/g, ' ').split(' ')
      .filter(w => w.length > 2 && !TITLE_STOP.has(w))
  );
}

/** Jaccard overlap of two titles' content words. */
export function titleSimilarity(a: string, b: string): number {
  const A = titleTokens(a), B = titleTokens(b);
  if (A.size === 0 || B.size === 0) return 0;
  let inter = 0;
  for (const w of A) if (B.has(w)) inter += 1;
  return inter / (A.size + B.size - inter);
}

