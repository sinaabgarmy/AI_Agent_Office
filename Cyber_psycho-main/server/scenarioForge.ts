export type ScenarioOrigin = 'vault-seed' | 'surface' | 'path' | 'intel' | 'graph' | 'hunter';

export interface ForgedScenario {
  id: string;
  title: string;
  category: string;
  briefing: string;
  targetArchitecture: string;
  coreHypothesis: string;
  defaultInvolvedBots: string[];
  origin: ScenarioOrigin;
  layer?: string;
  cwe?: string;
  severity?: string;
  sourceUrl?: string;
  /** 0..1 — how much a debate on this is expected to teach. */
  score: number;
  /** Why the forge picked it, in one line. */
  rationale: string;
  autoGenerated: true;
  generatedAt: string;
  /** Extra origin-specific fields preserved for the existing UI badges. */
  [extra: string]: unknown;
}

export interface TopicLike { id: string; title: string; autoGenerated?: boolean; savedAt?: string }

interface ForgeState {
  /** Every scenario id the forge has ever produced. */
  generated: string[];
  /** Ids the operator deleted — never offered again. */
  dismissed: string[];
  log: Array<{ at: string; generated: number; candidates: number; byOrigin: Record<string, number> }>;
  lastRunAt: string | null;
}

const STATE_FILE = 'scenario-forge-state.json';
const SCENARIO_DIR = '13-Scenarios';

/** Which agents lead a hunt in each layer. Red-team roles go first. */
export const HUNTER_AGENTS_BY_LAYER: Record<string, string[]> = {
  'Cryptography': ['entropy', 'zerocipher', 'stateroot'],
  'Consensus': ['consensusghost', 'vesper', 'sentinel'],
  'Execution': ['vesper', 'bytecode', 'darkpool'],
  'Economic': ['darkpool', 'vesper', 'bytecode'],
  'L2 / Bridge': ['stateroot', 'vesper', 'zerocipher'],
  'Governance': ['darkpool', 'bytecode', 'vesper'],
  'Infrastructure': ['vesper', 'entropy', 'consensusghost'],
  'Supply Chain': ['vesper', 'bytecode', 'entropy'],
  'Key Management': ['entropy', 'zerocipher', 'vesper'],
};

const CATEGORY_BY_LAYER: Record<string, string> = {
  'Consensus': 'Consensus Flaw',
  'Cryptography': 'Cryptographic Vulnerability',
  'Execution': 'Smart Contract Exploit',
  'Economic': 'Economic Attack',
  'L2 / Bridge': 'L2 Rollup Security',
  'Governance': 'Governance Attack',
  'Infrastructure': 'Infrastructure Attack',
  'Supply Chain': 'Supply Chain Attack',
  'Key Management': 'Key Management',
};

const SEVERITY_WEIGHT: Record<string, number> = { Critical: 1, High: 0.8, Medium: 0.6 };

/** Puts a layer's registered specialists (Agent Foundry / seed agents) at the head of the cast. */
function castFor(layer: string | undefined, base: string[]): string[] {
  const extra = layer ? extraAgentsForLayer(layer) : [];
  return [...extra, ...base].filter((v, i, a) => a.indexOf(v) === i).slice(0, 4);
}

